#!/usr/bin/env node
// Protect the distinction between the 1731 Company submission, its 1889 certified copy, and actual payment.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const load = name => JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'data', name + '.json'), 'utf8'));
const docs = new Map(load('archival_documents').map(x => [x.id, x]));
const sources = new Map(load('sources').map(x => [x.id, x]));
const entities = new Map(load('entities').map(x => [x.id, x]));
const extracts = load('source_extracts');
const audit = load('louisiana_claim_direction_audit');
const images = load('louisiana_image_access_audit');
const flows = load('financial_flows');
const cases = load('cases');
const events = load('events');
function validate(state) {
  const doc=state.docs.get('doc-021'), extract=state.extracts.find(x=>x.id==='extract-015');
  const claim=state.audit.claims.find(x=>x.id==='claim-1731-company-to-crown-retrocession-submission');
  const access=state.images.find(x=>x.id==='access-lcd-1731-01-24-03');
  const entity=state.entities.get('ent-natchez-nation');
  const caseRecord=state.cases.find(x=>x.id==='retrocession1731');
  const event=state.events.find(x=>x.id==='evt-1731-jan-retrocession-document');
  assert(doc&&extract&&claim&&access&&entity&&caseRecord&&event,'Missing 24 January record component');
  assert.equal(doc.date,'1731-01-24');
  assert.equal(doc.access_level,'certified_archival_copy_text_examined');
  assert(/1889 certified archival copy/i.test(doc.title));
  assert(/underlying 1731 Company register was not examined/i.test(doc.limitations));
  assert(doc.entities.includes('ent-natchez-nation'));
  assert(doc.entities.includes('ent-enslaved-africans-french-louisiana'));
  assert(!doc.entities.includes('ent-french-superior-council-la'),'Do not promote catalogue label into authorship');
  assert(doc.sources.includes('src-lcd-indexing-method-and-wpa'));
  assert(doc.sources.includes('src-natchez-nation-official'));
  assert(doc.sources.includes('src-nps-natchez-history'));
  const source=state.sources.get('src-lcd-retrocession-1731');
  assert(source&&source.reviewed===true&&source.url==='https://lacolonialdocs.org/document/2003');
  assert(/125283.*125285/.test(source.locator));
  const french=extract.transcription_pages.map(p=>p.text).join('\n');
  assert(/Trois millions six cent mille livres/.test(french));
  assert(/Quatorze cent cinquante mille livres seulement/.test(french));
  assert(/soumission de payer la susdite somme/.test(french));
  assert(/cinq cent nègres par an/.test(french));
  assert.equal(extract.reading_level,'certified_archival_copy_text_examined');
  const nums=new Map(extract.reported_numbers.map(n=>[n.value,n]));
  assert(nums.has(3600000)&&nums.has(1450000)&&nums.has(500));
  assert(/estimate/.test(nums.get(3600000).meaning));
  assert(/not an actual shipment/.test(nums.get(500).meaning));
  assert.equal(200000*3+150000*3+100000*4,1450000,'Installment schedule must sum to fixed amount');
  assert.equal(claim.document,'doc-021');
  assert.equal(claim.claim_direction,'company_authorized_submission_to_pay_french_crown_as_retrocession_equivalent');
  assert.equal(claim.amount_reported.value,1450000,'Do not promote the 3,600,000 estimate to fixed amount');
  assert.equal(claim.amount_reported.unit,'livres_as_written_not_normalized');
  assert.equal(claim.amount_reported.verification,'certified_copy_transcribed_not_payment');
  assert.equal(claim.amount_verified,false);
  assert.equal(claim.liability_adjudicated,false);
  assert.equal(claim.payment_verified,false);
  assert(/not established/.test(claim.relation_to_doc_024));
  assert.equal(access.observed_on,'2026-11-24');
  assert.equal(access.examined_image_count,24);
  assert.equal(access.unexamined_image_link_count,24);
  assert.equal(access.full_resolution_asset_verified,false);
  assert.equal(access.wpa_black_book_crosswalk_verified,false);
  assert.equal(access.copy_certification_date,'1889-09-20');
  assert(access.examined_image_derivatives.some(x=>x.image_id==='125284'));
  assert(access.examined_image_derivatives.some(x=>x.image_id==='125285'));
  assert(entity.sources.includes('src-natchez-nation-official'));
  assert(caseRecord.entities.includes('ent-natchez-nation'));
  assert(event.entities.includes('ent-natchez-nation'));
  assert(event.entities.includes('ent-enslaved-africans-french-louisiana'));
  assert(!state.flows.some(f=>(f.sources||[]).includes('src-lcd-retrocession-1731')),'Do not create a financial flow from the undertaking');
}
validate({docs,sources,entities,extracts,audit,images,flows,cases,events});
const bad=mutate=>{
 const state={docs:new Map(docs),sources:new Map(sources),entities:new Map(entities),extracts:structuredClone(extracts),audit:structuredClone(audit),images:structuredClone(images),flows:structuredClone(flows),cases:structuredClone(cases),events:structuredClone(events)};
 mutate(state); assert.throws(()=>validate(state));
};
bad(s=>{s.audit.claims.find(x=>x.id==='claim-1731-company-to-crown-retrocession-submission').amount_reported.value=3600000;});
bad(s=>{s.audit.claims.find(x=>x.id==='claim-1731-company-to-crown-retrocession-submission').payment_verified=true;});
bad(s=>{s.audit.claims.find(x=>x.id==='claim-1731-company-to-crown-retrocession-submission').liability_adjudicated=true;});
bad(s=>{s.docs.get('doc-021').access_level='original_1731_manuscript_text_examined';});
bad(s=>{s.images.find(x=>x.id==='access-lcd-1731-01-24-03').full_resolution_asset_verified=true;});
bad(s=>{s.images.find(x=>x.id==='access-lcd-1731-01-24-03').wpa_black_book_crosswalk_verified=true;});
console.log('OK: 24 January Company-register extract remains an 1889 certified copy; 1,450,000-livre undertaking is not a verified liability/payment; proposed 500-person supply is not a shipment');
